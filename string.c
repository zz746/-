int StringInsert(Str *s,int pos,Str *t){
    if(pos<1||pos>s->length+1||s->length+t->length>100){
        return 0;
    }
    for(int i=1;i<=t->length;i++){
        for(int j=s->length;j>=pos+i-1;j--){
            s->data[j+1]=s->data[j];
        }
        s->data[pos+i-1]=t->data[i];
        s->length++;
    }
    s->data[s->length+1]='\0';
    return 1;
}
