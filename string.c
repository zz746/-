 /* 二、需要自行实现的操作
 *
 * 1. 初始化 / 清空
 *    将串设为空串；既可用于首次初始化，也可清空已有内容的串。
 *    不要求把整个字符数组清零，只要满足空串的存储约定。
 */
void StringInit(Str *string){
    string->length=0;
    string->data[string->length+1]='\0';
}
 /* 2. 从 C 字符串赋值
 *    接收目标顺序串和只读的 C 字符串。
 *    输入长度为 0..100 时完整复制，更新长度，补好结束符，返回 1。
 *    输入超过 100 个字符时返回 0，目标串原来的内容和长度均不变。
 *    不允许截断后当作成功，也不允许先覆盖目标再发现超长。
 *    不修改输入字符串；其他操作接收的串都已成功初始化。
 */
int StingInput(Str *a,char b[]){
    int len=0;
    while (b[len]!='\0'){
        len++;
    }
    if(len>100){
        return 0;
    }
    a->length=0;
    int i=0;
    while(b[i]!='\0'){
        a->data[++a->length]=b[i++];
    }
    a->data[a->length+1]='\0';
    return 1;
}
