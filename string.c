int SString(Str *S,Str *T){
    if(T->length>S->length||(S->length==0&&T->length!=0)){
        return 0;
    }
    if(T->length==0){
        return 1;
    }
    int i=1;
    while(i<=S->length-T->length+1){
        int t=i;
        for(int j=1;j<=T->length;j++){
            if(S->data[t]!=T->data[j]){
                i++;
                break;
            }
            if(j==T->length){
                return i;
            }
            t++;
        }
    }
    return 0;
}
