int Stringlink(Str *a,Str *b,Str *c){
    if(a->length+b->length>100){
        return 0;
    }
    int len;
    if(!StringEmpty(a,&len)){
        for(int i=1;i<=len;i++){
            c->data[i]=a->data[i];
        }
    }
    if(!StringEmpty(b,&len)){
        for(int i=1;i<=len;i++){
            c->data[i+a->length]=b->data[i];
        }
    }
    c->length=a->length+b->length;
    c->data[c->length+1]='\0';
    return 1;
}
 /* 三、2B：求子串
 * - 接收输入串 S、起始位置 pos、字符数量 count，以及输出串 T。
 * - T 是与 S 存储独立的对象，不要求原地截取。
 * - pos 合法范围为 1..S.length+1；count 必须 >= 0，
 *   且不能超过从 pos 到原串末尾的剩余字符数量。
 * - count 为 0 时得到空串；pos 为 S.length+1 时只允许 count 为 0。
 * - 成功后替换 T 的旧内容；失败时 T 不变，S 始终不变。
 * 验收：S="abcdef"，(pos,count)=(2,3) 得 "bcd"；
 *       (1,6) 得原串，(6,1) 得 "f"，(7,0) 得空串。
 *       (0,1)、(8,0)、(6,2)、(1,-1) 均失败。
 *       对空串，(1,0) 成功，(1,1) 失败。
 */
int StrSubstring(Str *s,int pos,int count,Str *T){
    if(pos>s->length+1||pos<1||count>s->length+1-pos||count<0){
        return 0;
    }
    for(int i=pos;i<=pos+count-1;i++){
        T->data[i-pos+1]=s->data[i];
    }
    T->length=count;
    T->data[T->length+1]='\0';
    return 1;
}

