#include <stdio.h>
#define Maxsize 100

typedef struct{
    int data[Maxsize];
    int length;
}SqList;

void InitLsit(SqList *l){
    l->length=0;
}

void PrintLsit(SqList l){
    if(l.length==0){
        printf("\n");
        return;
    }
    for(int i=0;i<l.length;i++){
        if(i==0){
            printf("%d",l.data[i]);
        }else{
            printf(" %d",l.data[i]);
        }
    }
    printf("\n");
    return;
}

