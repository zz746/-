 int Sqdelete(SqList *list,int pos){
    if(pos<0||pos>=list->length||list->length==0){
        return 0; 
    }
    for(int i=0;i<list->length-1;i++){
        if(i>=pos){
            list->data[i]=list->data[i+1];
        }
    }
    list->length--;
    return 1;
 }

