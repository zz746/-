int Sqinsert(SqList *list,int pos,int value){
    if(pos<0||pos>list->length){
        return 0;
    }
    if(list->length>=Maxsize){
        printf("full");
        return 0;
    }
    for(int i=list->length-1;i>=pos;i--){
        list->data[i+1]=list->data[i];
    }
    list->data[pos]=value;
    list->length++;
    return 1;
}

