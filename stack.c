#include<stdio.h>
#define Maxsize 100

typedef struct Stack{
    int stack[Maxsize];
    int top;
}Stack;

 /* A. 初始化。
 * - 将栈设置为空栈，不必清零整个数组。
 * - 再次初始化已有元素的栈后，应恢复为空栈。
 */
void StackInit(Stack *stack){
    stack->top=-1;
}

 /* B. 判空。
 * - 空栈返回 1，非空返回 0，不改变栈。
 */
int StackEmpty(Stack *stack){
    if(stack->top==-1){
        return 1;
    }
    return 0;
}
 /* C. 入栈。
 * - 接收栈和整数 value，只能将新值放到新的栈顶。
 * - 成功返回 1；栈满返回 0，原有数据和 top 保持不变。
 * - 正确更新 top，避免写入数组下标 -1 或容量对应的越界位置。
 * - 不移动已有元素，单次入栈的时间复杂度应为 O(1)。
 * - 函数名、参数名和传参方式由你决定，修改必须作用于调用者的栈。
 */
int Stackpush(Stack *stack,int value){
    if(stack->top<Maxsize-1){
        stack->stack[stack->top+1]=value;
        stack->top++;
        return 1;
    }
    return 0;
}
