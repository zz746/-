#include<stdio.h>
#define Maxsize 10
typedef struct matrix{
    /* data */
    int n;
    int data[((1+Maxsize)*Maxsize)/2];
}matrix;

 /* A. 压缩。
 * - 接收有效二维数组、实际阶数 n，以及用于保存结果的结构体指针。
 * - 合法阶数为 1 到最大阶数；合法输入约定已经对称，不必检查对称性。
 * - 成功时记录 n，并按上述顺序保存下三角，返回 1。
 * - n 非法时返回 0，结果结构体保持原状。
 * - 输入二维数组不得修改，未使用的压缩数组位置不要求清零。
 */

int Squeese(int g[Maxsize][Maxsize],int n,matrix *matrix){
    int num=0;
    if(n<=0||n>Maxsize){
        return 0;
    }
    for(int i=0;i<n;i++){
        for(int j=0;j<=i;j++){
            matrix->data[num++]=g[i][j];
        }
    }
    matrix->n=n;
    return 1;
}
/* B. 读取。
 * - 接收已成功压缩的结构体、行下标 i、列下标 j 和 int 输出指针。
 * - 下标均合法时，通过输出指针带回 A[i][j]，返回 1。
 * - 任一下标为负数或大于等于 n 时，返回 0，输出变量保持不变。
 * - 不能解压整张矩阵，也不能扫描压缩数组寻找目标，应直接计算下标。
 * - 对上三角位置，利用对称性转换到已保存的下三角位置。
 * - 读取函数不修改压缩结构体，时间复杂度 O(1)。
 * - 相关指针均约定有效，输出变量独立于输入和压缩结构体。
 */
int Read(matrix *matrix,int i,int j,int *value){
    if(i>matrix->n-1||j>matrix->n-1||i<0||j<0){
        return 0;
    }
    if(i>=j){
        *value=matrix->data[(((1+i)*i)/2+j)];
        return 1;
    }
    if(i<j){
        *value=matrix->data[(((1+j)*j)/2+i)];
        return 1;
    }
}
