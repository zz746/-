/*
 * 特殊矩阵第 2 题——三角矩阵（未完成，第 1 题通过后再做）
 *
 * 与对称矩阵不同，上三角和下三角不互为镜像，不能交换 i、j 读取。
 * - 本题约定：下三角矩阵在主对角线以上的元素全等于常量 c；
 *   上三角矩阵在主对角线以下的元素全等于 c，c 可以不为 0。
 * - 使用独立的压缩结构体，保存阶数 n、上/下三角类型和压缩数组。
 * - 按行保存选定三角区域（含主对角线），再在有效数据最后一个位置
 *   保存一次常量 c；共 n*(n+1)/2 + 1 个槽，数组容量由最大阶数推导。
 * - 输入二维数组固定尺寸与第 1 题一致，合法 n 为 1..最大阶数。
 * - 压缩函数接收输入、n、三角类型、c 和结果指针；约定常量区域符合 c，
 *   不必逐个验证。n 或类型非法返回 0，结果不变；成功返回 1。
 * - 读取函数下标非法返回 0，输出不变；合法返回 1，并带回元素。
 * - 三角区域内直接计算压缩位置，区域外读常量槽，读取 O(1)。
 * - 输入只读，无动态内存，不保存原始完整二维矩阵。
 */
typedef struct matrix_c{
    /* data */
    int n;
    int data[((1+Maxsize)*Maxsize)/2+1];
}matrix_c;

int Squeese_c(int g[Maxsize][Maxsize],int n,int type,int c,matrix_c *matrix){
    if(n<=0||n>Maxsize){
        return 0;
    }
    if(type=0){
        int num=0;
        for(int i=0;i<n;i++){
            for(int j=0;j<=i;j++){
                matrix->data[num++]=g[i][j];
            }
        }
        matrix->data[num]=c;
        return 1;
    }else if(type=1){
        int num=0;
        for(int i=0;i<n;i++){
            for(int j=0;j<=matrix->n-i;j++){
                matrix->data[num++]=g[i][j];
            }
        }
        matrix->data[num]=c;
        return 1;
    }
}

int Read_c(matrix_c *matrix,int i,int j,int type,int *value){
    if(i>matrix->n-1||j>matrix->n-1||i<0||j<0){
        return 0;
    }
    if(type=0){
        if(i>=j){
            *value=matrix->data[(((1+i)*i)/2+j)];
            return 1;
        }else{
            return matrix->data[((1+matrix->n)*matrix->n)/2];
        }
        
    }
    if(type=1){
        if(i<=j){
            *value=matrix->data[(matrix->n+(matrix->n-i+1))*i+j-i+1];
            return 1;
        }else{
            return matrix->data[((1+matrix->n)*matrix->n)/2];
        }
        
    }
}

