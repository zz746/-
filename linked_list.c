#include<stdlib.h>
#include<stdio.h>

typedef struct linked_list{
    /* data */
    struct linked_list *next;
    int data;
}linked_list;

linked_list *LinkInit(void){
    linked_list *h=malloc(sizeof(linked_list));
    if(h==NULL){
        return NULL;
    }
    h->next=NULL;
    return h;
}

int Linkaddend(linked_list *list,int value){
    linked_list *p=malloc(sizeof(linked_list));
    if(p==NULL){
        return 0;
    }
    p->data=value;
    linked_list *q=list;
    while (q->next!=NULL){
        q=q->next;
    }
    q->next=p;
    p->next=NULL;
    return 1;
}

void LinkPrint(linked_list *h){
    linked_list *p=h;
    if(p->next!=NULL){
        printf("%d",p->next->data);
        p=p->next;
    }
    while(p->next!=NULL){
        p=p->next;
        printf(" %d",p->data);
    }
    printf("\n");
}

void LinkFree(linked_list *h){
    linked_list *f=h,*p=h;
    while(f!=NULL){
        p=f->next;
        free(f);
        f=p;
    }
}

int main(void){
    linked_list *h=LinkInit();
    if (h!=NULL)
    {
        printf("h!=NULL");
        LinkPrint(h);
    }else
    return 1;
    LinkFree(h);
    h=NULL;
    return 0;
}
